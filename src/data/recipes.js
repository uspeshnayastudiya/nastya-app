const r1 = (v) => Math.round(v * 10) / 10;

export const RECIPES = RAW.map(([name, role, method, minutes, list]) => {
  let kcal = 0, p = 0, f = 0, c = 0, g = 0;
  const ingredients = list.map(([food, grams]) => {
    const v = FOODS[food];
    if (!v) throw new Error('Нет продукта: ' + food);
    kcal += (v[0] * grams) / 100;
    p += (v[1] * grams) / 100;
    f += (v[2] * grams) / 100;
    c += (v[3] * grams) / 100;
    g += grams;
    return { name: food, g: grams, dept: v[4] };
  });
  return { name, role, method, minutes, portion_g: g, kcal: r1(kcal), p: r1(p), f: r1(f), c: r1(c), ingredients };
});
